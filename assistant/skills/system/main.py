class SystemSkill(Skill):
    def match(self, text: str) -> Intent | None:
        for action, pattern in _PATTERNS:
            if m := pattern.search(text):
                if action == "joke" and not (self.app.pack and self.app.pack.has("joke")):
                    return None  # no recorded jokes: let the model joke
                if action == "recall_more" and not self.app.brain.recalling():
                    continue     # "раньше" / "а ещё" mean something else without a recall just before
                slots = {k: v for k, v in m.groupdict().items() if v}
                if action == "correct":
                    slots = {"rest": next(iter(slots.values()))}
                return Intent(self.name, action, slots, text=text)
        return None

    async def handle(self, intent: Intent) -> Reply:
        now = dt.datetime.now()
        address = self.app.cfg.assistant.address
        match intent.action:
            case "stop":
                self.app.interrupt()
                return Reply(listen_after=False)
            case "thanks":
                return Reply(f"Всегда к вашим услугам, {address}.", reaction="thanks", listen_after=False)
            case "insult":
                return Reply(f"Очень тонкое замечание, {address}.", reaction="stupid", listen_after=False)
            case "joke":
                return Reply("Шутки кончились.", reaction="joke")
            case "time":
                return Reply(f"Сейчас {now.hour}:{now.minute:02d}.", listen_after=False)
            case "date":
                return Reply(f"Сегодня {_WEEKDAYS[now.weekday()]}, {now.day} {_MONTHS[now.month - 1]}.", listen_after=False)
            case "repeat":
                last = self.app.speaker.last_text
                return Reply(last or "Я пока ничего не говорил.")
            case "again":
                return await self.app.brain.redo()
            case "recall":
                which, n = str(intent.slots.get("which", "")), str(intent.slots.get("n", ""))
                back = 2 if which.startswith("позапрошл") else _NUMBERS.get(n, 1)
                more = any(w in intent.text for w in ("до этого", "перед этим", "раньше"))
                return self.app.brain.recall(more=more, back=back)
            case "recall_more":
                return self.app.brain.recall(more=True)
            case "rerun":
                return await self.app.brain.rerun()
            case "history":
                return self.app.brain.history()
            case "correct":
                return await self.app.brain.correct(str(intent.slots["rest"]))
            case "wrong":
                return await self.app.brain.undo_last(forget=True)
            case "undo":
                return await self.app.brain.undo_last(forget=False)
            case "mute":
                self.app.set_muted(True)
                return Reply("Выключаю микрофон. Включить можно в трее или сочетанием Ctrl Alt K.", listen_after=False)
            case "unmute_mic":
                self.app.set_muted(False)
                return Reply("Слушаю.", reaction="reply", listen_after=False)
            case "help":
                return Reply("Коротко: отвечаю на вопросы с поиском в интернете, открываю и закрываю программы, "
                             "управляю окнами, звуком и музыкой, ставлю таймеры и помодоро, веду заметки и списки, "
                             "помню факты о вас, диктую текст, работаю с выделенным текстом и экраном, "
                             "говорю погоду и расписание. Полный список — в файле MODULES.")
            case "exit":
                self.app.request_exit()
                return Reply(spoken=True, listen_after=False)
        return Reply()


def create() -> Skill:
    return SystemSkill()
